# ==============================================================================
# 2. CORRECTED & ROBUST VERSION (TESTED & DEBUGGED WITHOUT AI)
# ==============================================================================
def corrected_version(db_path=DB_FILE):
    """
    Corrected, production-ready implementation that resolves all AI shortcomings:
    - Verifies database file existence upfront with user-friendly error message.
    - Corrects SQL clause order: GROUP BY followed by HAVING and ORDER BY.
    - Uses floating-point precision with division-by-zero safeguards for revenue share.
    - Gracefully handles empty query results before any plotting operations.
    - Formats horizontal bar chart with labels, titles, gridlines, and revenue callouts.
    """
    print("\n" + "=" * 75)
    print("SECTION D: AI-AUGMENTED LEARNING (CORRECTED & DEBUGGED VERSION)")
    print("=" * 75)

    # 1. Database File Existence Check
    if not os.path.exists(db_path):
        print(f"[ERROR] Database file '{db_path}' does not exist.")
        print("Please check the database path or run Task 4 / Section C to initialize the database.")
        return

    # 2. Database Connection & Query Execution
    try:
        conn = sqlite3.connect(db_path)
        
        # Correct SQL Clause Order: FROM -> JOIN -> GROUP BY -> HAVING -> ORDER BY -> LIMIT
        sql_query = """
        SELECT 
            r.name AS restaurant_name,
            r.category,
            COUNT(o.order_id) AS order_count,
            ROUND(AVG(o.rating), 2) AS avg_rating,
            ROUND(SUM(o.order_value), 2) AS total_revenue
        FROM restaurants r
        JOIN orders o 
            ON r.restaurant_id = o.restaurant_id
        GROUP BY 
            r.restaurant_id, 
            r.name,
            r.category
        HAVING 
            COUNT(o.order_id) >= 4  -- Filter restaurants with sufficient order volume
        ORDER BY 
            avg_rating DESC
        LIMIT 3;
        """
        df = pd.read_sql_query(sql_query, conn)
        conn.close()

    except sqlite3.Error as err:
        print(f"[DATABASE ERROR] Failed to query SQLite database: {err}")
        return

    # 3. Handle Case Where Query Returns No Rows
    if df.empty:
        print("\n[NOTIFICATION] The query returned 0 rows.")
        print("No restaurants met the minimum order volume threshold (>= 4 orders).")
        print("Skipping plotting to prevent program failure.")
        return

    print(f"\n[1] Top 3 Restaurants by Average Rating (Retrieved {len(df)} records):")
    print(df.to_string(index=False))

    # 4. Safe Calculation of Combined Revenue Share Percentage
    total_top3_revenue = df['total_revenue'].sum()
    if total_top3_revenue > 0:
        df['revenue_share_pct'] = (df['total_revenue'].astype(float) / float(total_top3_revenue)) * 100.0
    else:
        df['revenue_share_pct'] = 0.0

    print("\n" + "-" * 75)
    print("[2] Ranked Restaurants with Combined Revenue Share:")
    for _, row in df.iterrows():
        print(f"  * {row['restaurant_name']} ({row['category']}): "
              f"Rating: {row['avg_rating']:.2f}/5.0 | "
              f"Revenue: ${row['total_revenue']:,.2f} ({row['revenue_share_pct']:.1f}% share)")

    # 5. Plot Horizontal Bar Chart
    plt.figure(figsize=(9, 5))
    # Invert order so highest ranked is at the top
    plot_df = df.iloc[::-1].reset_index(drop=True)
    
    bars = plt.barh(plot_df['restaurant_name'], plot_df['avg_rating'], color='#2b5c8f', edgecolor='black', height=0.55)
    
    # Chart styling & labels
    plt.title("Top 3 Restaurants by Customer Rating\n(with Top 3 Revenue Share %)", fontsize=13, fontweight='bold', pad=12)
    plt.xlabel("Average Customer Rating (out of 5.0)", fontsize=11, fontweight='bold')
    plt.ylabel("Restaurant Name", fontsize=11, fontweight='bold')
    plt.xlim(0, 5.5)
    plt.grid(axis='x', linestyle='--', alpha=0.5)

    # Add revenue share percentage as bar labels
    for bar, (_, row) in zip(bars, plot_df.iterrows()):
        width = bar.get_width()
        label_text = f"★ {width:.2f}  |  Rev Share: {row['revenue_share_pct']:.1f}% (${row['total_revenue']:,.0f})"
        plt.text(width + 0.1, bar.get_y() + bar.get_height() / 2.,
                 label_text,
                 ha='left', va='center',
                 fontsize=10, fontweight='bold', color='#1a252f')

    plt.tight_layout()
    plt.savefig(CHART_FILE, dpi=150, bbox_inches='tight')
    plt.close()

    print("\n" + "-" * 75)
    print(f"[3] Chart Saved Successfully: '{os.path.abspath(CHART_FILE)}'")
    print("=" * 75)
    print("SECTION D TASK COMPLETED SUCCESSFULLY.")
    print("=" * 75)

